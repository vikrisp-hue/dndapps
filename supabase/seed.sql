“Вы добыли Пакт и принесли его. Вы нашли путь через горы. Вы видели Оракулов и вернулись не с паникой, а с результатом. Поэтому этот свиток несёте вы.”
Мира добавляет:
“И потому что если кто-то должен стоять рядом с кратером, который сейчас заметят все заинтересованные стороны, лучше пусть это будут люди, уже умеющие выживать там, где не должны.”
Каэл:
“И потому что ваш замок ближе всех к точке удара.”
