8. Эльминстр репетирует речь
Эльминстр здесь должен быть живым, молодым, перегруженным, но вдохновлённым.
Он не “дед-архимаг из будущего”. Он молодой опасный маг, который понимает, что сейчас ему предстоит сыграть роль, которая может войти в историю.
И он гордится игроками. Не сладко, не пафосно, а по-настоящему: они сделали то, что даже Имаскар не смог.
Сцена
Игроки видят Эльминстра в соседней комнате или у края зала.
Он стоит перед пустым пространством и репетирует речь.
В воздухе перед ним то появляется силуэт наутилоида, то исчезает. Иногда он выглядит слишком страшно, иногда слишком театрально. Эльминстр раздражённо щёлкает пальцами, меняет форму щупалец, угол тени, высоту “корабля”.
Он бормочет:
“Нет, слишком красиво. Люди не боятся красивого, они потом это рисуют на кружках…”
Или:
“Если щупальца ниже — площадь увидит. Если выше — дворяне увидят. Мне нужны оба. Проклятье.”
Потом замечает игроков.
“А вот и вы.”
Пауза.
“Живые. С Пактом. После гор, Оракулов и всего того, что, судя по вашему виду, я пока не хочу знать за завтраком.”
Он улыбается устало, но искренне.
“Хорошая работа.”
Если игроки удивятся, что он хвалит:
“Не привыкайте. Я всё ещё считаю вас катастрофой с ногами. Но сегодня вы были нашей катастрофой. Это приятно.”
Эльминстр гордится игроками
Он говорит уже тише:
“Вы понимаете, что сделали? Не для Имаскара. Не для Ашерона. Для карты. Вы дошли туда, куда все привыкли не доходить, и принесли обратно вещь, которая заставит взрослых людей в дорогих плащах переписывать прошлое.”
Потом ещё мягче:
“Это редкий вкус. Запомните. Обычно история переписывает таких, как вы. Сегодня вы притащили ей чернила.”
Предложение выпить
Эльминстр может предложить после всего выпить.
“Когда всё это закончится — барьер, город, наутилоид, речи, возможная паника, возможные казни, возможная война, — я предлагаю выпить.”
Если кто-то спрашивает, за что:
“За то, что мы будем живы. Не оригинально, зато практично.”
Потом добавляет:
“И за вас. Потому что, как бы мне ни хотелось этого не признавать, без вас мы бы до сих пор спорили с картами.”
Это хорошая человеческая сцена. Она делает Эльминстра не только опасным магом, но и будущим союзником, который эмоционально понимает вес момента.
