7. Лиреана: план спектакля и политической сцены
Лиреана остаётся как в моей прошлой версии, но можно расширить.
Она понимает: простое разрушение барьера не даст управляемой победы. Люди Цурлагола не станут автоматически свободными. Они испугаются, запаникуют, начнут искать старую власть, старых жрецов, старые объяснения.
Поэтому нужна постановка.
Не потому что Имаскар не верит в правду. А потому что Имаскар не верит, что правда сама умеет говорить.
Лиреана объясняет план
“Когда барьер падёт, люди увидят не свободу. Они увидят, что вся их жизнь стояла на лжи. Это не просветляет. Это ломает.”
Она указывает на Цурлагол.
“Если в этот момент старая власть первой даст объяснение, она выживет. Она скажет: ‘Это нападение. Это кара. Это демоны. Это иллюзия врагов’. И половина города поверит, потому что верить старому ужасу легче, чем новой правде.”
Потом она смотрит в сторону Эльминстра.
“Поэтому объяснение дадим мы.”
Спектакль с наутилоидом
План Лиреаны:
•	после падения барьера Цурлагол должен увидеть угрозу;
•	угроза будет оформлена как иллюзорное вторжение наутилоида;
•	Эльминстр публично “отразит” его;
•	люди увидят, что иллитидская угроза реальна или хотя бы возможна;
•	старая власть будет выглядеть беспомощной;
•	Имаскар появится как сила, способная защитить город;
•	после этого последует заявление.
Лиреана честно говорит:
“Мы не можем выйти к толпе и сказать: ‘Добрый день, ваши карты лгали, ваш горизонт был клеткой, ваши советники служат пожирателям разума, а мы нашли древнюю бумагу, которая делает нас удобной альтернативой власти’. Это плохая речь. Её перебьют камнями.”
Если игроки возмутятся, что это новая ложь, она не спорит:
“Да. Это сцена. Но сцена, которая ведёт людей к правде, иногда полезнее правды, которая ведёт людей к панике.”
Каэл может резко добавить:
“Или мы можем сказать всё прямо и смотреть, как город сам несёт головы Оракулам, потому что те хотя бы обещают вернуть привычный мир.”
Лиреана:
“Столетнюю ложь нельзя разбить одной правдивой фразой. Её нужно заменить историей, которую люди смогут пережить.”
