9. Севериан делает портальный камень
Севериан в начале сцены отсутствует, потому что он работает.
Его нужно ввести отдельно, с сильным визуалом.
Мастерская Севериана
Игроков проводят или вызывают в боковую мастерскую.
Там хаос другого типа: не политический, а технический.
На столах:
•	схемы из документов Саэля;
•	нетерильские формулы;
•	каменные заготовки;
•	металлические кольца;
•	сосуды с жидким светом;
•	обломки старого портального узла;
•	инструменты Имаскара;
•	защитные круги;
•	карта между особняком и замком.
В центре — камень, который ещё не портал, но уже не просто камень.
Он зависает в воздухе, дрожит, по его поверхности ползут трещины света. Пространство рядом с ним слегка “складывается”: стол за камнем кажется ближе, чем должен быть.
Севериан выглядит как человек, который трижды забыл поесть и считает это нормой.
Текст для зачтения
В мастерской пахнет горячим камнем, озоном и чернилами.

Севериан стоит у рабочего круга, где в воздухе висит серый камень размером с человеческую голову. По его поверхности расходятся тонкие светящиеся жилы. Иногда они раскрываются, и на миг вы видите не внутренность камня, а кусок другого места: мокрый камень, знакомую стену, край замковой кладки.

Севериан не оборачивается сразу.

“Нет, нет, нет… если развернуть складку до стабилизации, он порвёт не расстояние, а полмастерской…”

Потом замечает вас.

“О. Вы вернулись. Великолепно. Не трогайте ничего, что светится. И ничего, что не светится, тоже.”
Севериан объясняет камни
“Документы из вашего замка оказались не инструкцией к готовой сети, а описанием принципа. Нетерил не телепортировал людей так, как любят рассказывать сказки. Он складывал расстояние между двумя подготовленными точками.”
