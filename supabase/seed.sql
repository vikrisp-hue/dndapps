“Откроете ларец только на месте. Перстень укажет, когда вы достаточно близко.”
Лиреана:
“И, пожалуйста, постарайтесь не выглядеть слишком довольными, когда будете менять ландшафт. Хотя понимаю, просьба трудная.”
