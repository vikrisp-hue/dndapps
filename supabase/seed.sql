16. Падение барьера
Описание
На несколько секунд нет ничего. Ни ветра. Ни гула. Ни эха. Даже камни, кажется, забывают падать.

Потом горизонт трескается.

Там, где раньше стоял хребет, которого не было на старых картах, появляется тонкая белая линия. Она бежит по скалам, как трещина по стеклу.

Хребет становится плоским. Ненастоящим. Слишком ровным. Слишком послушным.

Потом он рвётся.

За ним не появляется новый мир. Вы понимаете это почти сразу. Он не появляется. Он всегда был там.

Дальние земли. Дороги. Дым. Силуэты башен. Море, которое не заканчивается мёртвым обрывом.

Ложь не исчезает красиво. Она осыпается грязной серой пылью с края зрения. И впервые за сто лет горизонт не предлагает вам поверить ему на слово.
Снаружи
Можно вставить короткую кинематографичную нарезку, даже если игроки её не видят напрямую:
Где-то далеко караванщик на старой дороге останавливает лошадь, потому что выжженная пустошь впереди вдруг становится зелёным плато.

На корабле у побережья матрос роняет кружку, увидев там, где был мёртвый обрыв, городские стены и берег.

В Цурлаголе старик смотрит за городскую черту и впервые за жизнь видит не конец мира, а дорогу.

И никто ещё не понимает, что война уже стала неизбежной.
17. Финальный кадр
Игроки стоят на плато у замка.
За спиной — их замок, теперь официально признанный Имаскаром. Рядом — первый портал. Внизу — кратер, повторно уничтоженный Метеоритным дождём. Впереди — настоящий горизонт.
Можно закончить так:
Мир стал больше.

И от этого не стало безопаснее.
Или:
Цурлагол больше не последний город живого мира.

Он просто первый, кто узнает, что его клетка открыта.
