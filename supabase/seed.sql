6. Каэл готовит план эскалации и признаёт игроков владельцами замка
Каэл в этой сцене должен быть воодушевлён. Не “добрый друг”, а человек, который видит: события наконец вышли из стадии архивов в стадию действия.
Он уже готовит план, потому что понимает: после разрушения барьера Цурлагол может среагировать паникой, насилием или попыткой закрыть город.
Что делает Каэл
На карте он отмечает:
•	подходы к Цурлаголу;
•	старые дороги;
•	замок игроков;
•	кратер лимитирующих камней;
•	потенциальные маршруты войск;
•	точки эвакуации;
•	места, где можно поставить будущие порталы;
•	участки, где Оракулы могут спровоцировать панику;
•	направления возможного бегства городских властей.
Он говорит:
“Если барьер падает, у нас будет от часа до суток, пока Цурлагол не поймёт, что именно потерял. Потом начнутся приказы, аресты, закрытие ворот, охота на свидетелей и попытка объявить всё ересью.”
Каэл смотрит на игроков:
“Поэтому мы готовим не праздник истины. Мы готовим эскалацию.”
План Каэла
Первый уровень: наблюдение и слухи. Серые Ключи фиксируют реакцию города.
Второй уровень: защита ключевых свидетелей. Людей, которые видели внешний мир или знают про Оракулов, нужно спрятать.
Третий уровень: силовое окно. Если власти Цурлагола начнут массовые чистки, Имаскар должен быть готов ударить по их центрам связи, архивам и городским воротам.
Четвёртый уровень: удержание замка игроков. Замок на плато становится стратегическим узлом. Особенно после установки портала.
Официальное признание замка
Это важный момент.
Каэл и Ашерон официально признают игроков владельцами замка.
Не “мы разрешаем вам там жить”, а именно: Дом Имаскар признаёт факт владения.
Ашерон говорит:
“Замок Альбина более не является ничейной заставой.”
Каэл продолжает:
“Вы удержали его. Вы сделали его точкой возврата. Вы нашли в нём документы, которые меняют регион. Дом Имаскар признаёт вас владельцами замка.”
Ашерон:
“Не по древнему праву. Не по милости рода. По факту владения и способности удержать.”
Каэл:
“Если Цурлагол, Оракулы или кто-либо ещё оспорит это, пусть приходит не с бумагой, а с армией.”
Это прям важная награда. Игроки получают не только Пакт как выполненный квест, но и официальное признание своего первого дома.
Если хочешь сделать ещё сильнее, можно дать формулировку:
“С этого дня в наших внутренних записях замок Альбина значится как находящийся под властью вашей стороны. Как вы назовёте эту сторону — ваше дело.”
Это аккуратно открывает дверь к Дому Тэй, не навязывая название.
