15. Каст Метеоритного дождя с плато
Перед кастом
Игроки поднимаются к точке обзора. Они видят кратер лимитирующих камней.
Он может выглядеть как знакомая странная локация:
•	выжженная земля;
•	левитирующие камни;
•	старый кратер;
•	чёрные обломки;
•	ощущение, что магия там не работает правильно;
•	лёгкое мерцание воздуха;
•	возможно, тот самый ложный хребет на горизонте.
Перстень нагревается.
Ларец открывается.
Описание ларца
Перстень касается замка на крышке ларца. Четыре печати Имаскара вспыхивают одна за другой. Металл на миг становится прозрачным, будто внутри не пустота, а кусок ночного неба.

Ларец открывается сам.

Внутри лежит свиток, намотанный на тёмный каменный стержень. Бумага не желтеет, не шуршит и не кажется старой. Она похожа на высушенную кожу грозового облака. На ней горят четыре маленькие точки.
Активация
Когда свиток разворачивается, ветер над плато меняется. Не усиливается — меняет направление сразу несколько раз, будто мир пытается понять, откуда сейчас придёт удар.

Над кратером небо становится слишком ясным. Облака расходятся кругами.

Высоко-высоко, почти за пределом зрения, появляются четыре белые точки.

Сначала они кажутся звёздами.

Потом звёзды начинают падать.
Удар
Первый удар попадает в центр кратера. Земля поднимается, как вода от брошенного камня, только вместо брызг — огонь, пыль и чёрная порода.

Второй удар разрывает край кратера, где висели левитирующие обломки. На мгновение они вспыхивают изнутри и падают все разом.

Третий удар проходит по линии лимитирующих камней. Вы не видите сам камень под землёй, но видите, как воздух над ним складывается, будто кто-то сжал невидимую ткань.

Четвёртый удар бьёт туда, где кратер переходит в старую трещину плато. И после него звук исчезает.
