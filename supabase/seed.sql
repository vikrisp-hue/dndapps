3. Нижний зал карт
Образ зала
Это большой зал без окон. В центре — огромный стол с картами. Над ним висят полупрозрачные слои иллюзий: старые карты Нетерила, цурлагольские карты, карты Саэля, новые расчёты Севериана, линии порталов, предполагаемые границы Ложного Края.
Часть карт не совпадает физически. Одна и та же река на разных слоях течёт по-разному. Там, где одна карта показывает хребет, другая показывает дорогу. Там, где цурлагольская карта заканчивается мёртвым краем, старый нетерильский слой показывает живые пути.
У стола:
•	Ашерон Имаскар — неподвижный, холодный, но напряжённый.
•	Каэл Имаскар — в дорожной/военной одежде, с пометками на карте, готовит план эскалации.
•	Лиреана Имаскар — рядом со стопкой писем и набросков будущих заявлений.
•	Мира Вейн — отдаёт тихие инструкции агентам Серых Ключей.
•	несколько шпионов/слуг/писцов — получают задачи.
•	Эльминстр может быть в соседнем зале или у стены, репетируя речь.
•	Севериана сначала нет: он занят портальным камнем в мастерской.
Текст для зачтения
Нижний зал карт похож не на кабинет, а на вскрытое тело мира.

На длинном столе лежат карты, наложенные одна на другую. Некоторые написаны чернилами. Некоторые светятся. Некоторые ползут по воздуху тонкими линиями, будто сами не уверены, где должны проходить дороги.

В одном месте карта Цурлагола показывает серую пустошь. Старый нетерильский слой под ней показывает дорогу. Ещё глубже — значок города, которого на нынешних картах быть не должно.

У стола стоит Ашерон. Он не кричит и не отдаёт резких приказов, но вокруг него все двигаются так, будто каждое его молчание уже решение.

Каэл чертит на карте линии возможных ударов и отступлений. Лиреана диктует сразу два письма разным писцам. Мира Вейн говорит с тремя людьми так тихо, что вы понимаете только отдельные слова: “порт”, “архив”, “слухи”, “никого не убивать без нужды”.

И только через несколько секунд кто-то наконец смотрит на вас по-настоящему.
