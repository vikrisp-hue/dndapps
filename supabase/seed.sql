<p class="p2"><b>Место</b></p>
<p class="p3">Главная площадь <b>Цурлагола</b>.</p>
<p class="p3">Старые знамёна ещё не сняты полностью. На некоторых башнях висят старые гербы города, но поверх них уже закрепляют новые полотна Имаскара: не как украшение, а как заявление.</p>
<p class="p3">В центре площади построена большая деревянная сцена. Не праздничная — скорее временный суд, трибуна и место казни одновременно. На заднике сцены закреплён большой развёрнутый щит с новым знаком Имаскара.</p>
<p class="p3">На сцене:</p>
<p class="p4">•<span class="Apple-tab-span">	</span><b>Лорд Ашерон Имаскар</b>;</p>
<p class="p4">•<span class="Apple-tab-span">	</span><b>Каэл Имаскар</b>;</p>
<p class="p4">•<span class="Apple-tab-span">	</span><b>Севериан Имаскар</b>;</p>
<p class="p4">•<span class="Apple-tab-span">	</span><b>Лиреана Имаскар</b>;</p>
<p class="p4">•<span class="Apple-tab-span">	</span><b>Эльминстр</b>;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>несколько новых чиновников и писцов;</p>
<p class="p4">•<span class="Apple-tab-span">	</span><b>магистрат Эллар Дорн</b>;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>рядом, чуть в стороне, стоят <b>игроки</b> и <b>Мира Вейн</b>.</p>
<p class="p3">Важно: игроки и Мира находятся близко к центру событий, но пока не представлены. Они видят документы, слышат реплики, стоят в зоне власти — но толпа пока не понимает, кто они в новой системе.</p>
<p class="p3">Внизу:</p>
<p class="p4">•<span class="Apple-tab-span">	</span>жители города;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>бывшие рабы;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>ремесленники;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>старые чиновники;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>солдаты;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>люди из подземных районов;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>тифлинги, пока осторожно стоящие у края площади;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>первые чужаки снаружи, которые пришли посмотреть, что за город внезапно “вернулся” на карту.</p>
<p class="p3">Настроение толпы не радостное. Оно раскалённое.</p>
<p class="p3">Кто-то ждёт освобождения. Кто-то ждёт расправы. Кто-то боится Имаскара больше старой власти. Кто-то просто хочет понять, кто теперь хозяин.</p>
<p class="p5">​</p>
<p class="p1"><b>Открытие сцены</b></p>
<p class="p3">Ашерон выходит без лишней театральности. Он не машет рукой, не улыбается, не пытается нравиться.</p>
<p class="p3">Он кладёт перед собой футляр с <b>Пактом владения регионом</b>.</p>
<p class="p3">И начинает не с победы, а с лжи.</p>
<p class="p6">“Сто лет вам говорили, что мир умер.”</p>
<p class="p7"><br></p>
<p class="p6">“Сто лет вам говорили, что за горизонтом пустошь, обрыв и смерть.”</p>
<p class="p7"><br></p>
<p class="p6">“Сто лет власть этого города называла клетку спасением.”</p>
<p class="p7"><br></p>
<p class="p6">“Сегодня клетка открыта.”</p>
<p class="p3">Толпа шумит. Кто-то кричит, кто-то требует назвать виновных, кто-то рыдает.</p>
<p class="p3">Ашерон не повышает голос.</p>
<p class="p6">“Я не прошу вас поверить мне на слово. Слишком долго вами правили словами.”</p>
<p class="p3">Он даёт знак Севериану.</p>
<p class="p3">Писцы разворачивают копии документов: карты, отчёты, старые приказы, записи о Ложном Крае, документы о подавлении внешних сведений.</p>
<p class="p6">“Перед вами документы. Карты старого мира. Отчёты о ложном горизонте. Реестры уничтоженных экспедиций. Приказы о сокрытии внешних дорог.”</p>
<p class="p7"><br></p>
<p class="p6">“Вам не просто лгали. Вас выращивали внутри лжи.”</p>
<p class="p5">​</p>
<p class="p1"><b>Заявление первое: Пакт и смена власти</b></p>
<p class="p3">Ашерон вскрывает футляр с Пактом не полностью для толпы, а ритуально: показывает печати, древний акт, подписи, юридические символы Нетерила.</p>
<p class="p3">Севериан стоит рядом и подтверждает подлинность.</p>
<p class="p6">“Перед вами <b>Пакт владения регионом</b>. Древний акт, составленный до нынешней власти, до нынешних магистратов, до той лжи, которая сделала этот город тюрьмой.”</p>
<p class="p7"><br></p>
<p class="p6">“Этим Пактом подтверждается право на управление землями, которые старая власть удерживала без знания, без правды и без согласия тех, кем правила.”</p>
<p class="p3">Толпа реагирует тяжело. Для многих это просто новая бумага от новых хозяев.</p>
<p class="p3">Ашерон это понимает.</p>
<p class="p6">“Документ сам по себе не делает власть справедливой. Но он делает ложь старой власти незаконной.”</p>
<p class="p3">Пауза.</p>
<p class="p6">“С этого дня город <b>Цурлагол</b> прекращает существовать как столица столетней лжи.”</p>
<p class="p3">Он поднимает взгляд на толпу.</p>
<p class="p6">“Отныне этот город будет называться <b>Великий Имаскар</b>.”</p>
<p class="p3">Шум. Крики. Часть людей повторяет новое имя. Часть откровенно в ужасе.</p>
<p class="p6">“Я, <b>Ашерон Имаскар</b>, принимаю титул <b>Первого Лорда Великого Имаскара</b>.”</p>
<p class="p5">​</p>
<p class="p1"><b>Заявление второе: отмена рабства</b></p>
<p class="p3">Вот это должно прозвучать первым крупным законом, чтобы толпа поняла: смена власти не только про гербы.</p>
<p class="p3">Ашерон кладёт на стол пачку старых городских реестров.</p>
<p class="p6">“Первый закон Великого Имаскара прост.”</p>
<p class="p7"><br></p>
<p class="p6">“Рабство отменяется.”</p>
<p class="p3">Пауза. Толпа на секунду не понимает, что услышала.</p>
<p class="p6">“С этого дня ни один человек, тифлинг, эльф, полуорк, гоблин, дварф или представитель иной разумной крови не может быть признан собственностью другого лица.”</p>
<p class="p7"><br></p>
<p class="p6">“Все долговые цепи, наследственные узы, рабские метки, городские реестры владения телом и трудом — аннулируются.”</p>
<p class="p3">Крики. Уже настоящие. Кто-то падает на колени. Кто-то из бывших владельцев начинает возмущаться.</p>
<p class="p3">Каэл делает шаг вперёд, и его люди на площади сразу напрягаются.</p>
<p class="p3">Ашерон продолжает:</p>
<p class="p6">“Те, кто удерживает рабов после этого заявления, будут признаны мятежниками против нового порядка.”</p>
<p class="p7"><br></p>
<p class="p6">“Те, кто освобождён сегодня, не обязаны благодарить меня. Свобода не милость. Милостью её называли те, кто крал её у вас.”</p>
<p class="p3">Это сильный момент: он не просит любви. Он берёт власть через закон.</p>
<p class="p5">​</p>
<p class="p1"><b>Заявление третье: подземные жители</b></p>
<p class="p3">После отмены рабства Ашерон обращается к тем, кто жил под городом: беглые, изгнанники, подземные общины, преступные группы, бывшие рабы, люди без статуса.</p>
<p class="p6">“Теперь я обращаюсь к тем, кто живёт под этим городом.”</p>
<p class="p7"><br></p>
<p class="p6">“К тем, кого загнали в тоннели. К тем, кто прятался от долговых цепей, от старой стражи, от ложных обвинений, от голода или от собственной вины.”</p>
<p class="p3">Он делает паузу.</p>
<p class="p6">“Великий Имаскар предлагает переговоры.”</p>
<p class="p3">Толпа реагирует неоднозначно. Кто-то кричит: “Там убийцы!” Кто-то: “Там наши дети!” Кто-то: “Они нас грабили!”</p>
<p class="p3">Ашерон не спорит.</p>
<p class="p6">“Среди вас есть невиновные. Среди вас есть беглые рабы. Среди вас есть люди, которых старая власть превратила в грязь, а потом удивлялась, что грязь кусается.”</p>
<p class="p7"><br></p>
<p class="p6">“Но среди вас есть и мерзавцы. Убийцы. Торговцы людьми. Те, кто сделал подземелья своим маленьким царством страха.”</p>
<p class="p3">Он смотрит в сторону входов в нижние районы, будто говорит не только с толпой, но и с теми, кто слушает из-под земли.</p>
<p class="p6">“Поэтому предложение одно: выходите на переговоры.”</p>
<p class="p7"><br></p>
<p class="p6">“Не на казнь. Не на поклон. На переговоры.”</p>
<p class="p7"><br></p>
<p class="p6">“Те, кто хочет жить на свету, получат такую возможность.”</p>
<p class="p7"><br></p>
<p class="p6">“Те, кто хочет продолжать править страхом внизу, узнают, что у нового города есть достаточно длинные руки.”</p>
<p class="p3">Это создаёт идеальный конфликт на будущие задания: часть подземных жителей благодарна и выйдет; часть преступников попытается воспользоваться амнистией; часть начнёт войну за нижние районы.</p>
<p class="p5">​</p>
<p class="p1"><b>Заявление четвёртое: тифлинги больше не “демоны”</b></p>
<p class="p3">Теперь Ашерон переходит к самому взрывоопасному пункту.</p>
<p class="p3">На краю площади стоят представители тифлингов. Они не чувствуют себя в безопасности. Город веками называл их демонами.</p>
<p class="p3">Ашерон поднимает несколько документов.</p>
<p class="p6">“Теперь о тех, кого этот город называл демонами.”</p>
<p class="p3">Толпа мгновенно меняется. Шум становится резче. Кто-то плюёт. Кто-то отступает. Кто-то ищет глазами рогатые силуэты у края площади.</p>
<p class="p3">Ашерон говорит жёстче:</p>
<p class="p6">“Вам говорили, что тифлинги — порождения зла.”</p>
<p class="p7"><br></p>
<p class="p6">“Вам говорили, что с ними нельзя говорить.”</p>
<p class="p7"><br></p>
<p class="p6">“Вам говорили, что их кровь делает их рабами, врагами, скотом или угрозой по праву рождения.”</p>
<p class="p3">Он поднимает первый документ.</p>
<p class="p6">“Вот отчёт старого управления городской пропаганды.”</p>
<p class="p7"><br></p>
<p class="p6">“Цитата: ‘Программа демонизации рогатых племён идёт успешно. При сохранении текущего давления следующее поколение будет воспринимать собственное порабощение как естественное следствие крови’.”</p>
<p class="p3">Толпа гудит.</p>
<p class="p3">Он поднимает второй документ.</p>
<p class="p6">“Вот приказ о распространении слухов после нападения на караван. Виновные не были установлены. Но в приказе заранее указано: ‘В публичном изложении связать происшествие с демонами верхних троп’.”</p>
<p class="p3">Третий документ.</p>
<p class="p6">“Вот реестр детей, рождённых от смешанных связей. Пометка чиновника: ‘Не допускать к городским ремёслам. При необходимости использовать как доказательство разложения крови’.”</p>
<p class="p3">Четвёртый.</p>
<p class="p6">“Вот донесение о торговцах, которые пытались вести обмен с тифлингами. Их обвиняли не в преступлении, а в ‘ослаблении страха перед внешним видом врага’.”</p>
<p class="p3">Ашерон опускает документы.</p>
<p class="p6">“Это не правосудие. Это разведение ненависти.”</p>
<p class="p3">Он говорит громче:</p>
<p class="p6">“С этого дня прежние обвинения против племени тифлингов, основанные на их крови, происхождении, рогах, коже или старой городской пропаганде, сняты.”</p>
<p class="p7"><br></p>
<p class="p6">“Тифлинги могут входить в Великий Имаскар. Торговать. Давать показания. Искать защиты нового закона.”</p>
<p class="p7"><br></p>
<p class="p6">“Любой, кто нападёт на них только за то, что старая власть научила его бояться, будет отвечать перед новым судом.”</p>
<p class="p3">Очень важно: он не объявляет тифлингов невинными во всём. Он снимает именно расовую/пропагандистскую вину.</p>
<p class="p6">“Это не значит, что преступления будут прощены. Если тифлинг убил — он ответит как убийца. Если человек убил — он ответит как убийца. Но отныне кровь не является приговором.”</p>
<p class="p3">Вот это взрослый и сильный баланс, особенно с учётом того, что игроки знают про резню диких эльфов.</p>
<p class="p5">​</p>
<p class="p1"><b>Заявление пятое: публичная библиотека</b></p>
<p class="p3">Это должно стать неожиданностью даже для Имаскара.</p>
<p class="p3">Ашерон смотрит на толпу. Он видит настроение: страх, гнев, надежду, недоверие. Он понимает, что просто силой и документами новый порядок не удержать.</p>
<p class="p3">И тут он принимает решение на сцене.</p>
<p class="p3">Это заявление не знали заранее ни Каэл, ни Севериан, ни Лиреана, ни Мира.</p>
<p class="p3">Ашерон некоторое время молчит. Севериан чуть поворачивает голову, потому что понимает: отец сейчас отходит от подготовленной речи.</p>
<p class="p3">Ашерон говорит:</p>
<p class="p6">“И ещё одно.”</p>
<p class="p3">Лиреана впервые заметно напрягается.</p>
<p class="p6">“Сто лет вами правили не только мечом, страхом и ложными картами.”</p>
<p class="p7"><br></p>
<p class="p6">“Вами правили невежеством.”</p>
<p class="p3">Он смотрит на людей.</p>
<p class="p6">“Дом Имаскар хранил библиотеку. Старую. Неполную. Опасную. Дорогую. Достаточно большую, чтобы многие здесь назвали её сокровищницей.”</p>
<p class="p3">Севериан в этот момент реально в шоке. Для него библиотека — сердце рода.</p>
<p class="p3">Ашерон продолжает:</p>
<p class="p6">“Эта библиотека будет перенесена в Великий Имаскар.”</p>
<p class="p3">Толпа сначала не понимает. Потом начинается шум.</p>
<p class="p6">“Часть её станет общественной.”</p>
<p class="p7"><br></p>
<p class="p6">“Не для каждого праздного любопытного. Не для тех, кто ищет оружие в каждой строке. Но для тех, чья личность на хорошем счету, кто доказал намерение учиться, служить, лечить, строить, писать, считать, вести ремесло или искать правду.”</p>
<p class="p3">Севериан тихо, почти шёпотом:</p>
<p class="p6">“Отец…”</p>
<p class="p3">Ашерон не смотрит на него.</p>
<p class="p6">“Город, который сто лет держали во лжи, не станет свободным, если мы просто сменим вывеску на дворце.”</p>
<p class="p7"><br></p>
<p class="p6">“Знание больше не будет только стеной вокруг рода. Часть его станет лестницей для города.”</p>
<p class="p3">Это прям взрыв. Кто-то плачет. Кто-то не верит. Кто-то из старой знати в ужасе, потому что доступ к знаниям разрушает старые зависимости.</p>
<p class="p3">Лиреана быстро берёт себя в руки и уже понимает политическую гениальность этого жеста: Ашерон покупает не только власть, а будущее поколение чиновников, магов, инженеров и лояльных людей.</p>
<p class="p5">​</p>
<p class="p1"><b>Благодарность Эллару Дорну</b></p>
<p class="p3">Теперь Ашерон переходит к назначениям и благодарностям.</p>
<p class="p3">Он публично благодарит тех, кого можно легально показать.</p>
<p class="p6">“Магистрат <b>Эллар Дорн</b>.”</p>
<p class="p3">Эллар выходит или делает шаг вперёд. Для толпы он чиновник старого города, но теперь выясняется, что он помог раскрыть ложь.</p>
<p class="p6">“Ваше содействие, переданные документы и риск, на который вы пошли внутри старой администрации, позволили вскрыть часть заговора до того, как он стал войной.”</p>
<p class="p3">Это важный момент: Ашерон показывает, что не все в старой системе были врагами.</p>
<p class="p6">“Великий Имаскар будет нуждаться не только в новых людях, но и в тех, кто знал старую машину изнутри и не дал ей перемолоть остатки правды.”</p>
<p class="p3">Эллар получает должность, например:</p>
<p class="p3"><b>Магистр городских реестров и переходного права</b> или <b>Советник по гражданской администрации</b>.</p>
<p class="p5">​</p>
<p class="p1"><b>Назначения на сцене</b></p>
<p class="p2"><b>Каэл</b></p>
<p class="p6">“Каэл Имаскар назначается <b>Лордом-Маршалом дорог и городской защиты</b>.”</p>
<p class="p3">Функция: охрана дорог, новые заставы, подавление мятежей, защита открытого региона.</p>
<p class="p2"><b>Севериан</b></p>
<p class="p6">“Севериан Имаскар назначается <b>Хранителем Пакта и Главным Архиварием Великого Имаскара</b>.”</p>
<p class="p3">Функция: Пакт, документы, библиотека, нетерильские технологии, порталы.</p>
<p class="p3">Севериан всё ещё в шоке из-за библиотеки, но держится.</p>
<p class="p2"><b>Лиреана</b></p>
<p class="p6">“Лиреана Имаскар назначается <b>Леди Договоров и Голосом Великого Имаскара</b>.”</p>
<p class="p3">Функция: переговоры, внешние связи, купцы, первые отношения с открывшимся миром.</p>
<p class="p2"><b>Эльминстр</b></p>
<p class="p6">“Эльминстр, внешний союзник Дома и защитник города, получает должность <b>Первого Магистра</b>.”</p>
<p class="p3">Это звучит чуть пафосно, и Эльминстр может позже ворчать, что титул ужасно громкий.</p>
<p class="p5">​</p>
<p class="p1"><b>Почему он не упоминает Миру и игроков</b></p>
<p class="p3">Ашерон перебирает бумаги. Он доходит до следующего листа, но не зачитывает.</p>
<p class="p3">Игроки и Мира стоят рядом.</p>
<p class="p3">Ашерон слегка наклоняется к ним, не меняя выражения лица, и почти не двигая губами говорит:</p>
<p class="p6">“Ваши должности будут несколько секретны.”</p>
<p class="p7"><br></p>
<p class="p6">“Простите, что без огласки.”</p>
<p class="p3">Мира не выглядит удивлённой. Скорее наоборот: она бы обиделась, если бы её назвали публично.</p>
<p class="p3">Игроки могут почувствовать разницу:</p>
<p class="p3">Публично их могут назвать героями и владельцами замка, но настоящие должности, настоящая структура и настоящая власть будут объявлены позже — за закрытыми дверями.</p>
<p class="p5">​</p>
<p class="p1"><b>Признание земли игроков</b></p>
<p class="p3">Это можно сделать публично, но без раскрытия их будущей секретной роли.</p>
<p class="p3">Ашерон говорит:</p>
<p class="p6">“Также перед городом, Пактом и новым правом я признаю за добывшими Пакт владение <b>замком Альбина</b> и землями вокруг него.”</p>
<p class="p7"><br></p>
<p class="p6">“Двадцать пять гектаров вокруг старой заставы переходят под их управление и защиту.”</p>
<p class="p7"><br></p>
<p class="p6">“Этот замок будет стоять на дороге между старой ложью и открытым миром.”</p>
<p class="p3">Это публично. Их видят. Их запоминают. Божественность отзывается.</p>
<p class="p3">Но он не говорит: “Они будут главами новой имперской структуры”.</p>
<p class="p5">​</p>
<p class="p1"><b>Божественный отклик игроков</b></p>
<p class="p3">После признания и реакции толпы можно дать короткий внутренний момент.</p>
<p class="p6">Когда толпа поворачивается к вам, это не похоже на благодарность одного спасённого человека.</p>
<p class="p7"><br></p>
<p class="p6">Это тяжелее. Грязнее. Опаснее.</p>
<p class="p7"><br></p>
<p class="p6">На вас смотрят как на тех, кто принёс Пакт, кто стоял рядом с новым лордом, кто получил землю и имя на карте.</p>
<p class="p7"><br></p>
<p class="p6">Где-то внутри Искры отвечают. Не светом. Не голосом. Давлением.</p>
<p class="p7"><br></p>
<p class="p6">Мир не молится вам.</p>
<p class="p7"><br></p>
<p class="p6">Но впервые достаточно людей одновременно признают: вы теперь часть его власти.</p>
<p class="p3">Это не обязательно новый уровень божественности, но явный скачок влияния.</p>
<p class="p5">​</p>
<p class="p1"><b>Финал публичной сцены</b></p>
<p class="p3">Ашерон завершает:</p>
<p class="p6">“Сегодня Великий Имаскар не становится безопасным.”</p>
<p class="p7"><br></p>
<p class="p6">“Он становится настоящим.”</p>
<p class="p7"><br></p>
<p class="p6">“А настоящий город должен иметь дороги, закон, память и врагов, которых он не боится назвать.”</p>
<p class="p3">Он закрывает Пакт.</p>
<p class="p6">“Старая ложь закончилась. Новый порядок начинается сейчас.”</p>
<p class="p3">На этом площадь взрывается шумом.</p>
<p class="p3">Кто-то кричит имя Имаскара. Кто-то имя Ашерона. Кто-то требует наказать старую власть. Кто-то зовёт освобождённых рабов. Кто-то смотрит на тифлингов с ненавистью, но уже боится ударить. Кто-то спрашивает, как попасть в библиотеку. Кто-то тихо уходит в подземелья, чтобы предупредить тех, кто не собирается выходить на переговоры.</p>
<p class="p3">И где-то среди толпы Серые Ключи уже работают.</p>
<p class="p5">​</p>
<p class="p1"><b>Сцена после назначения: главная мэрия города</b></p>
<p class="p3">После публичной церемонии игроков и Миру приглашают в главную мэрию города.</p>
<p class="p3">Теперь это уже не площадь, не речь, не театр.</p>
<p class="p3">Это закрытая комната власти.</p>
<p class="p2"><b>Обстановка</b></p>
<p class="p3">Большой зал городской администрации. Старые символы Цурлагола ещё не сняты. На стене карта города. На столе новые печати. За окнами всё ещё слышен шум толпы.</p>
<p class="p3">В комнате:</p>
<p class="p4">•<span class="Apple-tab-span">	</span><b>Ашерон</b>;</p>
<p class="p4">•<span class="Apple-tab-span">	</span><b>Каэл</b>;</p>
<p class="p4">•<span class="Apple-tab-span">	</span><b>Севериан</b>;</p>
<p class="p4">•<span class="Apple-tab-span">	</span><b>Лиреана</b>;</p>
<p class="p4">•<span class="Apple-tab-span">	</span><b>Мира Вейн</b>;</p>
<p class="p4">•<span class="Apple-tab-span">	</span><b>игроки</b>;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>возможно, <b>Эльминстр</b>, если хочешь добавить живой комментарий;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>несколько писцов, которых потом выводят.</p>
<p class="p3">Ашерон ждёт, пока двери закроются.</p>
<p class="p3">Потом говорит:</p>
<p class="p6">“Теперь — о должностях, которые не выкрикивают с площади.”</p>
<p class="p5">​</p>
<p class="p1"><b>Назначение Миры</b></p>
<p class="p3">Ашерон смотрит на Миру.</p>
<p class="p6">“Мира Вейн.”</p>
<p class="p3">Она спокойно делает шаг вперёд.</p>
<p class="p6">“Серые Ключи перестают быть только наследственной сетью Дома Имаскар.”</p>
<p class="p7"><br></p>
<p class="p6">“С этого дня они становятся основой <b>Разведывательного корпуса Великого Имаскара</b>.”</p>
<p class="p3">Пауза.</p>
<p class="p6">“Вы становитесь его главой.”</p>
<p class="p3">Мира не кланяется низко. Просто принимает.</p>
<p class="p6">“Принято.”</p>
<p class="p3">Ашерон:</p>
<p class="p6">“Ваши задачи: внутренняя безопасность, внешняя разведка, выявление Оракулов, защита архивов, контроль слухов и наблюдение за теми, кто решит, что новый порядок можно купить так же легко, как старый.”</p>
<p class="p3">Мира:</p>
<p class="p6">“Мне понадобятся люди, которых публично не существует.”</p>
<p class="p3">Ашерон:</p>
<p class="p6">“Именно поэтому я не назвал вас со сцены.”</p>
<p class="p5">​</p>
<p class="p1"><b>Назначение игроков: Орден Защитников</b></p>
<p class="p3">Теперь Ашерон обращается к партии.</p>
<p class="p6">“Вы не чиновники. И не солдаты в строю.”</p>
<p class="p7"><br></p>
<p class="p6">“Это неудобно.”</p>
<p class="p7"><br></p>
<p class="p6">“И ценно.”</p>
<p class="p3">Он раскрывает новый документ.</p>
<p class="p6">“Великому Имаскару понадобится структура, способная делать то, что армия делает слишком громко, разведка слишком тайно, а администрация слишком медленно.”</p>
<p class="p3">Каэл добавляет:</p>
<p class="p6">“Руины. Чудовища. дороги, старые хранилища, пропавшие караваны, следы Оракулов, угрозы за пределами закона.”</p>
<p class="p3">Лиреана:</p>
<p class="p6">“И задачи, которые официально будут называться защитой региона, даже если на деле они окажутся грязнее.”</p>
<p class="p3">Ашерон:</p>
<p class="p6">“Создаётся <b>Орден Защитников Великого Имаскара</b>.”</p>
<p class="p2"><b>Что это такое</b></p>
<p class="p3">По факту это имперская гильдия авантюристов.</p>
<p class="p3">Но в мире это звучит солиднее:</p>
<p class="p4">•<span class="Apple-tab-span">	</span>структура для особых поручений;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>легальный способ нанимать авантюристов;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>инструмент зачистки руин и угроз;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>способ контролировать опасных людей;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>механизм выдачи заданий от власти;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>будущая сеть полевых агентов.</p>
<p class="p3">Ашерон:</p>
<p class="p6">“Он будет принимать заказы от города, Дома, дорог, внешних союзников и граждан, если угроза признана значимой.”</p>
<p class="p7"><br></p>
<p class="p6">“Но право высшего отбора, направления и допуска к самым опасным поручениям получаете вы.”</p>
<p class="p2"><b>Три главы структуры</b></p>
<p class="p3">Игроки становятся не просто членами, а тремя главами новой структуры.</p>
<p class="p3">Можно дать им общий титул:</p>
<p class="p3"><b>Основатели Ордена Защитников</b><b></b></p>
<p class="p3">Ашерон:</p>
<p class="p6">“Вы будете первыми главами Ордена.”</p>
<p class="p7"><br></p>
<p class="p6">“Не потому, что вы удобны.”</p>
<p class="p7"><br></p>
<p class="p6">“Потому что вы уже доказали, что способны идти туда, где удобные люди умирают или врут.”</p>
<p class="p3">Каэл:</p>
<p class="p6">“Вы будете получать задачи, которые нельзя доверить городской страже.”</p>
<p class="p3">Мира:</p>
<p class="p6">“И иногда задачи, о которых городская стража не должна знать.”</p>
<p class="p3">Лиреана:</p>
<p class="p6">“А публично вы будете теми, кто защищает дороги, руины, караваны и людей нового государства.”</p>
<p class="p3">Севериан:</p>
<p class="p6">“И теми, кто будет приносить мне всё, что выглядит древним, опасным или не должно лежать без присмотра.”</p>
<p class="p3">Эльминстр, если присутствует:</p>
<p class="p6">“Особенно если оно светится, шепчет или обещает власть. Такие вещи, как показывает практика, вы всё равно находите первыми.”</p>
<p class="p5">​</p>
<p class="p1"><b>Разделение ролей игроков внутри Ордена</b></p>
<p class="p3">Можно не назначать жёстко, но Ашерон может предложить рамку.</p>
<p class="p2"><b>Марина / гоблинша</b></p>
<p class="p6">“Расследования, слабые места, внедрение, работа с информацией. Ордену понадобится тот, кто видит трещины раньше, чем они становятся провалами.”</p>
<p class="p2"><b>Ваня / воин</b></p>
<p class="p6">“Прорыв, подавление угроз, мобильные операции. Когда нужно быстро ударить туда, где враг считал себя недосягаемым.”</p>
<p class="p2"><b>Лена / паладин</b></p>
<p class="p6">“Защита, удержание, полевая власть. Когда люди должны выжить не потому, что мир добр, а потому что кто-то встал между ними и смертью.”</p>
<p class="p3">Ашерон:</p>
<p class="p6">“Это не клятва рыцарей. Не братство героев. Не храм.”</p>
<p class="p7"><br></p>
<p class="p6">“Это инструмент нового государства.”</p>
<p class="p3">Пауза.</p>
<p class="p6">“Но каким он станет — зависит от вас.”</p>
<p class="p5">​</p>
<p class="p1"><b>Полномочия Ордена</b></p>
<p class="p3">Ашерон перечисляет кратко:</p>
<p class="p4">•<span class="Apple-tab-span">	</span>право брать задания от имени Великого Имаскара;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>право нанимать авантюристов и проводников;</p>
