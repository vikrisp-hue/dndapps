4. Передача Пакта
Игроки должны почувствовать: они сделали очень важное дело.
Они не забрали Пакт себе, не начали торговаться, не заявили “это наше”. Они принесли его в особняк. Для Имаскара это не “ну молодцы”, а политически важный показатель.
Ашерон
Ашерон смотрит на футляр/документ и говорит:
“Вы могли оставить его себе.”
Пауза.
“Не оставили.”
Ещё пауза.
“Это не делает вас безопасными. Но делает разговор возможным.”
Если игроки передают Пакт спокойно, Ашерон принимает его не лично в руки сразу, а через специальную ткань/поднос/печать. Это подчёркивает ценность и опасность документа.
“Пакт владения регионом. Древняя бумага, ради которой люди будут называть захват восстановлением порядка.”
Если кто-то из игроков спросит, будет ли Имаскар “возвращать законную власть”, Ашерон отвечает честно, но холодно:
“Законная власть — это власть, которая пережила достаточно свидетелей. Пакт даст нам свидетелей старше Цурлагола.”
Каэл
Каэл реагирует иначе. Он воодушевлён не романтически, а как военный, который наконец получил ключ к операции.
“Пакт у нас. Значит, Цурлагол можно не только штурмовать. Его можно лишить права стоять.”
Он смотрит на игроков более уважительно, чем раньше.
“Вы дошли до гор, забрали документ из-под носа Оракулов и вернулись. Это результат. Я уважаю результат.”
Лиреана
Лиреана не смотрит на Пакт как на бумагу. Она смотрит на него как на будущую сцену.
“Люди не поверят документу. Люди поверят моменту, в который документ им покажут.”
Она мягко улыбается.
“Власть редко начинается с права. Но право помогает власти выглядеть прилично.”
Мира
Мира смотрит на игроков дольше обычного.
Она не сразу говорит. Для неё важнее другое: она считала их нестабильным активом, но они принесли Пакт, не спрятали его и не попытались переиграть Имаскар в момент слабости.
Её первая фраза сухая:
“Вы вернулись с тем, что могли украсть.”
Затем тише:
“Я ошиблась не в том, что вы опасны. Я ошиблась в том, что вы обязательно будете глупы.”
Позже она извинится чуть прямее, но не сразу.
