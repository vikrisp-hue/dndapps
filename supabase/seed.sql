Потом воздух между трещинами проваливается внутрь, и вы видите замок. Не отражение. Не видение. Камень стены, холодный свет, знакомый угол двора.

Расстояние между особняком Имаскара и вашим замком становится толщиной в один шаг.
Севериан:
“Поздравляю. Вы только что получили не дверь. Вы получили первую артерию будущего региона.”
