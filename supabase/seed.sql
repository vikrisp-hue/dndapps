12. Ларец со свитком Метеоритного дождя
Образ
Ларец должен ощущаться как настоящее сокровище.
Он не большой, но очень тяжёлый. Матовый металл, тёмное дерево, серебряные швы, четыре печати Имаскара. На крышке нет украшений, только маленький знак, похожий на падающую звезду, заключённую в квадрат.
Рядом — перстень-ключ.
Текст Ашерона
“Это не награда.”
Пауза.
“Награды дают за завершённые дела. Ваше дело только стало достаточно большим, чтобы стоить таких расходов.”
