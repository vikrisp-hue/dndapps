<p class="p3">По коридорам несут тубусы, карты, ящики с инструментами, свёртки ткани, металлические футляры. В комнатах горит слишком много света. На столах лежат развернутые карты, часть из которых противоречит друг другу. Воздух пахнет воском, чернилами, горячим металлом и усталостью.</p>
<p class="p3">Игроков могут заметить не сразу.</p>
<p class="p3">Это важно: они пришли с Пактом, но Дом Имаскар уже настолько глубоко ушёл в последствия их находок, что даже их возвращение оказывается частью общей суеты.</p>
<p class="p2"><b>Текст для зачтения</b></p>
<p class="p6">Особняк встречает вас не тишиной.</p>
<p class="p7"><br></p>
<p class="p6">Двери открываются раньше, чем вы успеваете постучать, но за ними нет привычного спокойствия. По коридору почти бегут двое слуг с тубусами. Где-то в глубине дома слышен звон металла, резкий голос Каэла, чужие шаги, шелест карт и короткое раздражённое: “Нет, эта граница не может быть здесь”.</p>
<p class="p7"><br></p>
<p class="p6">На стенах горит слишком много ламп. В доме, где обычно каждый звук знал своё место, теперь всё движется.</p>
<p class="p7"><br></p>
<p class="p6">Хальвер Моу появляется из бокового прохода с таким лицом, будто конец света уже внесён в расписание, но пока идёт с опозданием.</p>
<p class="p7"><br></p>
<p class="p6">Он замечает вас, смотрит на следы гор, кровь, усталость, футляр с Пактом — и впервые за всё время делает паузу чуть дольше обычного.</p>
<p class="p7"><br></p>
<p class="p6">“О. Вы живы. Превосходно. Прошу простить дом за невежливость. Сегодня он занят концом столетней лжи.”</p>
<p class="p5">​</p>
<p class="p1"><b>2. </b><a href="dmref://6F693AAB-FEEE-448F-BDC6-5B16ACB629BF"><b>Хальвер Моу</b></a><b>: проводник в кипящий дом</b></p>
<p class="p3">Хальвер остаётся вежливым, но через его вежливость видно: ситуация чрезвычайная.</p>
<p class="p3">Он не расспрашивает игроков подробно в коридоре. Не требует немедленно отдать Пакт. Не пытается устроить церемонию.</p>
<p class="p3">Он просто говорит:</p>
<p class="p6">“Лорд <a href="dmref://32694CE8-CEA7-4A4F-95FE-005CAF66FE12">Ашерон</a> в нижнем зале карт. Леди Лиреана там же. Мастер Севериан в мастерской, но, полагаю, уже забыл, что у людей есть сон. Господин Каэл готовит худший сценарий. Господин Эльминстр репетирует лучший. Оба, как обычно, неприятны по-своему.”</p>
<p class="p3">Если игроки спрашивают, что происходит:</p>
<p class="p6">“Дом Имаскар получил слишком много правды за слишком короткое время. Это всегда выглядит неприлично.”</p>
<p class="p3">Хальвер ведёт их не в гостиную, а в нижние помещения особняка.</p>
<p class="p5">​</p>
<p class="p1"><b>3. Нижний зал карт</b></p>
<p class="p2"><b>Образ зала</b></p>
<p class="p3">Это большой зал без окон. В центре — огромный стол с картами. Над ним висят полупрозрачные слои иллюзий: старые карты Нетерила, цурлагольские карты, карты Саэля, новые расчёты Севериана, линии порталов, предполагаемые границы Ложного Края.</p>
<p class="p3">Часть карт не совпадает физически. Одна и та же река на разных слоях течёт по-разному. Там, где одна карта показывает хребет, другая показывает дорогу. Там, где цурлагольская карта заканчивается мёртвым краем, старый нетерильский слой показывает живые пути.</p>
<p class="p3">У стола:</p>
<p class="p4">•<span class="Apple-tab-span">	</span><a href="dmref://32694CE8-CEA7-4A4F-95FE-005CAF66FE12"><b>Ашерон Имаскар</b></a> — неподвижный, холодный, но напряжённый.</p>
<p class="p4">•<span class="Apple-tab-span">	</span><a href="dmref://5E6AFDCC-ACC4-4E11-9AAB-D25C9D41855F"><b>Каэл Имаскар</b></a> — в дорожной/военной одежде, с пометками на карте, готовит план эскалации.</p>
<p class="p4">•<span class="Apple-tab-span">	</span><a href="dmref://58BC2FAA-5D0D-404A-B01D-7DA2D7B26379"><b>Лиреана Имаскар</b></a> — рядом со стопкой писем и набросков будущих заявлений.</p>
<p class="p4">•<span class="Apple-tab-span">	</span><a href="dmref://9A29AC84-E72F-45C4-ABFA-03662920147B"><b>Мира Вейн</b> </a>— отдаёт тихие инструкции агентам Серых Ключей.</p>
<p class="p4">•<span class="Apple-tab-span">	</span><b>несколько шпионов/слуг/писцов</b> — получают задачи.</p>
<p class="p4">•<span class="Apple-tab-span">	</span><a href="dmref://C1A60094-1372-428F-8896-2F210FAB5DD5"><b>Эльминстр</b> </a>может быть в соседнем зале или у стены, репетируя речь.</p>
<p class="p4">•<span class="Apple-tab-span">	</span><a href="dmref://D13DFC29-354B-4A2E-86DB-8342AFB73049"><b>Севериана</b> </a>сначала нет: он занят портальным камнем в мастерской.</p>
<p class="p2"><b>Текст для зачтения</b></p>
<p class="p6">Нижний зал карт похож не на кабинет, а на вскрытое тело мира.</p>
<p class="p7"><br></p>
<p class="p6">На длинном столе лежат карты, наложенные одна на другую. Некоторые написаны чернилами. Некоторые светятся. Некоторые ползут по воздуху тонкими линиями, будто сами не уверены, где должны проходить дороги.</p>
<p class="p7"><br></p>
<p class="p6">В одном месте карта Цурлагола показывает серую пустошь. Старый нетерильский слой под ней показывает дорогу. Ещё глубже — значок города, которого на нынешних картах быть не должно.</p>
<p class="p7"><br></p>
<p class="p6">У стола стоит <a href="dmref://32694CE8-CEA7-4A4F-95FE-005CAF66FE12">Ашерон</a>. Он не кричит и не отдаёт резких приказов, но вокруг него все двигаются так, будто каждое его молчание уже решение.</p>
<p class="p7"><br></p>
<p class="p6">Каэл чертит на карте линии возможных ударов и отступлений. Лиреана диктует сразу два письма разным писцам. Мира Вейн говорит с тремя людьми так тихо, что вы понимаете только отдельные слова: “порт”, “архив”, “слухи”, “никого не убивать без нужды”.</p>
<p class="p7"><br></p>
<p class="p6">И только через несколько секунд кто-то наконец смотрит на вас по-настоящему.</p>
<p class="p5">​</p>
<p class="p1"><b>4. Передача Пакта</b></p>
<p class="p3">Игроки должны почувствовать: они сделали очень важное дело.</p>
<p class="p3">Они не забрали Пакт себе, не начали торговаться, не заявили “это наше”. Они принесли его в особняк. Для Имаскара это не “ну молодцы”, а политически важный показатель.</p>
<p class="p2"><a href="dmref://32694CE8-CEA7-4A4F-95FE-005CAF66FE12"><b>Ашерон</b><b></b></a></p>
<p class="p3">Ашерон смотрит на футляр/документ и говорит:</p>
<p class="p6">“Вы могли оставить его себе.”</p>
<p class="p3">Пауза.</p>
<p class="p6">“Не оставили.”</p>
<p class="p3">Ещё пауза.</p>
<p class="p6">“Это не делает вас безопасными. Но делает разговор возможным.”</p>
<p class="p3">Если игроки передают Пакт спокойно, <a href="dmref://32694CE8-CEA7-4A4F-95FE-005CAF66FE12">Ашерон</a> принимает его не лично в руки сразу, а через специальную ткань/поднос/печать. Это подчёркивает ценность и опасность документа.</p>
<p class="p6">“Пакт владения регионом. Древняя бумага, ради которой люди будут называть захват восстановлением порядка.”</p>
<p class="p3">Если кто-то из игроков спросит, будет ли Имаскар “возвращать законную власть”, <a href="dmref://32694CE8-CEA7-4A4F-95FE-005CAF66FE12">Ашерон</a> отвечает честно, но холодно:</p>
<p class="p6">“Законная власть — это власть, которая пережила достаточно свидетелей. Пакт даст нам свидетелей старше Цурлагола.”</p>
<p class="p2"><b>Каэл</b></p>
<p class="p3">Каэл реагирует иначе. Он воодушевлён не романтически, а как военный, который наконец получил ключ к операции.</p>
<p class="p6">“Пакт у нас. Значит, Цурлагол можно не только штурмовать. Его можно лишить права стоять.”</p>
<p class="p3">Он смотрит на игроков более уважительно, чем раньше.</p>
<p class="p6">“Вы дошли до гор, забрали документ из-под носа Оракулов и вернулись. Это результат. Я уважаю результат.”</p>
<p class="p2"><b>Лиреана</b></p>
<p class="p3">Лиреана не смотрит на Пакт как на бумагу. Она смотрит на него как на будущую сцену.</p>
<p class="p6">“Люди не поверят документу. Люди поверят моменту, в который документ им покажут.”</p>
<p class="p3">Она мягко улыбается.</p>
<p class="p6">“Власть редко начинается с права. Но право помогает власти выглядеть прилично.”</p>
<p class="p2"><b>Мира</b></p>
<p class="p3">Мира смотрит на игроков дольше обычного.</p>
<p class="p3">Она не сразу говорит. Для неё важнее другое: она считала их нестабильным активом, но они принесли Пакт, не спрятали его и не попытались переиграть Имаскар в момент слабости.</p>
<p class="p3">Её первая фраза сухая:</p>
<p class="p6">“Вы вернулись с тем, что могли украсть.”</p>
<p class="p3">Затем тише:</p>
<p class="p6">“Я ошиблась не в том, что вы опасны. Я ошиблась в том, что вы обязательно будете глупы.”</p>
<p class="p3">Позже она извинится чуть прямее, но не сразу.</p>
<p class="p5">​</p>
<p class="p1"><b>5. Мира Вейн отдаёт инструкции Серым Ключам</b></p>
<p class="p3">Мира должна ощущаться не как “NPC в углу”, а как человек, который уже двигает сеть.</p>
<p class="p3">Она говорит тихо, но игроки могут услышать часть приказов.</p>
<p class="p2"><b>Инструкции Миры</b></p>
<p class="p8"><a href="dmref://1DAAE06A-DCB9-4AC1-8D8C-23B9BC809710"><b>Роэну “Сухая Тень”</b><b></b></a></p>
<p class="p6">“Роэн. Дороги к Цурлаголу, старый тракт, подходы к портам. Никакой героики. Мне нужны глаза, не труп.”</p>
<p class="p3">Роэн:</p>
<p class="p6">“Если хвост?”</p>
<p class="p3">Мира:</p>
<p class="p6">“Пусть думает, что потерял тебя сам.”</p>
<p class="p8"><a href="dmref://09B71E58-B140-4419-9750-1729BB6C934B"><b>Талису Грею</b><b></b></a></p>
<p class="p6">“Талис. Подготовь три версии слуха. Первая — что внешний мир жив. Вторая — что власть Цурлагола скрывала дороги. Третья — что древний род уже знал, но ждал доказательств. Третью использовать только после сигнала Лиреаны.”</p>
<p class="p3">Талис:</p>
<p class="p6">“С подписью?”</p>
<p class="p3">Мира:</p>
<p class="p6">“Без. Люди верят слухам лучше, когда думают, что украли их сами.”</p>
<p class="p8"><a href="dmref://E18971E6-98CA-499E-8CF0-81C0AA22E95D"><b>Йордану Крею</b><b></b></a></p>
<p class="p6">“Йордан. Не трогать городских крикунов без приказа. Нужны не исчезновения, а страх перед исчезновениями.”</p>
<p class="p3">Йордан усмехается.</p>
<p class="p3">Мира:</p>
<p class="p6">“Я сказала — без приказа.”</p>
<p class="p8"><a href="dmref://AEC47513-02F1-403A-A0FD-6198FC76AC06"><b>Эллару Дорну</b></a><b> через курьера/записку</b></p>
<p class="p6">“Эллару передать: сжечь только вторые копии. Первые пусть найдут не те люди. И пусть найдут слишком поздно.”</p>
<p class="p3">Это показывает: Имаскар уже готовит информационную войну.</p>
<p class="p2"><b>Мира позже извиняется перед игроками</b></p>
<p class="p3">После основной сцены, когда суета чуть стихает, Мира может подойти отдельно.</p>
<p class="p3">Не на публике. Не театрально.</p>
<p class="p6">“Я не доверяла вам.”</p>
<p class="p3">Пауза.</p>
<p class="p6">“Это было разумно.”</p>
<p class="p3">Ещё пауза.</p>
<p class="p6">“Но вы принесли Пакт. Не продали, не спрятали, не попытались открыть чужими руками. Значит, я должна исправить оценку.”</p>
<p class="p3">Если игроки ждут извинения:</p>
<p class="p6">“Не ждите красивых слов. Я редко ими пользуюсь. Но да — в этом я была неправа.”</p>
<p class="p3">И потом важная фраза:</p>
<p class="p6">“С этого момента я буду считать вас не наёмниками, а стороной. Это опаснее. Но честнее.”</p>
<p class="p5">​</p>
<p class="p1"><b>6. Каэл готовит план эскалации и признаёт игроков владельцами замка</b></p>
<p class="p3">Каэл в этой сцене должен быть воодушевлён. Не “добрый друг”, а человек, который видит: события наконец вышли из стадии архивов в стадию действия.</p>
<p class="p3">Он уже готовит план, потому что понимает: после разрушения барьера Цурлагол может среагировать паникой, насилием или попыткой закрыть город.</p>
<p class="p2"><b>Что делает Каэл</b></p>
<p class="p3">На карте он отмечает:</p>
<p class="p4">•<span class="Apple-tab-span">	</span>подходы к Цурлаголу;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>старые дороги;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>замок игроков;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>кратер лимитирующих камней;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>потенциальные маршруты войск;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>точки эвакуации;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>места, где можно поставить будущие порталы;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>участки, где Оракулы могут спровоцировать панику;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>направления возможного бегства городских властей.</p>
<p class="p3">Он говорит:</p>
<p class="p6">“Если барьер падает, у нас будет от часа до суток, пока Цурлагол не поймёт, что именно потерял. Потом начнутся приказы, аресты, закрытие ворот, охота на свидетелей и попытка объявить всё ересью.”</p>
<p class="p3">Каэл смотрит на игроков:</p>
<p class="p6">“Поэтому мы готовим не праздник истины. Мы готовим эскалацию.”</p>
<p class="p2"><b>План Каэла</b></p>
<p class="p3"><b>Первый уровень:</b> наблюдение и слухи. Серые Ключи фиксируют реакцию города.</p>
<p class="p3"><b>Второй уровень:</b> защита ключевых свидетелей. Людей, которые видели внешний мир или знают про Оракулов, нужно спрятать.</p>
<p class="p3"><b>Третий уровень:</b> силовое окно. Если власти Цурлагола начнут массовые чистки, Имаскар должен быть готов ударить по их центрам связи, архивам и городским воротам.</p>
<p class="p3"><b>Четвёртый уровень:</b> удержание замка игроков. Замок на плато становится стратегическим узлом. Особенно после установки портала.</p>
<p class="p2"><b>Официальное признание замка</b></p>
<p class="p3">Это важный момент.</p>
<p class="p3">Каэл и <a href="dmref://32694CE8-CEA7-4A4F-95FE-005CAF66FE12">Ашерон</a> официально признают игроков владельцами замка.</p>
<p class="p3">Не “мы разрешаем вам там жить”, а именно: Дом Имаскар признаёт факт владения.</p>
<p class="p3"><a href="dmref://32694CE8-CEA7-4A4F-95FE-005CAF66FE12">Ашерон</a> говорит:</p>
<p class="p6">“Замок Альбина более не является ничейной заставой.”</p>
<p class="p3">Каэл продолжает:</p>
<p class="p6">“Вы удержали его. Вы сделали его точкой возврата. Вы нашли в нём документы, которые меняют регион. Дом Имаскар признаёт вас владельцами замка.”</p>
<p class="p3"><a href="dmref://32694CE8-CEA7-4A4F-95FE-005CAF66FE12">Ашерон</a>:</p>
<p class="p6">“Не по древнему праву. Не по милости рода. По факту владения и способности удержать.”</p>
<p class="p3">Каэл:</p>
<p class="p6">“Если Цурлагол, Оракулы или кто-либо ещё оспорит это, пусть приходит не с бумагой, а с армией.”</p>
<p class="p3">Это прям важная награда. Игроки получают не только Пакт как выполненный квест, но и <b>официальное признание своего первого дома</b>.</p>
<p class="p3">Если хочешь сделать ещё сильнее, можно дать формулировку:</p>
<p class="p6">“С этого дня в наших внутренних записях замок Альбина значится как находящийся под властью вашей стороны. Как вы назовёте эту сторону — ваше дело.”</p>
<p class="p3">Это аккуратно открывает дверь к <b>Дому Тэй</b>, не навязывая название.</p>
<p class="p5">​</p>
<p class="p1"><b>7. Лиреана: план спектакля и политической сцены</b></p>
<p class="p3">Лиреана остаётся как в моей прошлой версии, но можно расширить.</p>
<p class="p3">Она понимает: простое разрушение барьера не даст управляемой победы. Люди Цурлагола не станут автоматически свободными. Они испугаются, запаникуют, начнут искать старую власть, старых жрецов, старые объяснения.</p>
<p class="p3">Поэтому нужна постановка.</p>
<p class="p3">Не потому что Имаскар не верит в правду. А потому что Имаскар не верит, что правда сама умеет говорить.</p>
<p class="p2"><b>Лиреана объясняет план</b></p>
<p class="p6">“Когда барьер падёт, люди увидят не свободу. Они увидят, что вся их жизнь стояла на лжи. Это не просветляет. Это ломает.”</p>
<p class="p3">Она указывает на Цурлагол.</p>
<p class="p6">“Если в этот момент старая власть первой даст объяснение, она выживет. Она скажет: ‘Это нападение. Это кара. Это демоны. Это иллюзия врагов’. И половина города поверит, потому что верить старому ужасу легче, чем новой правде.”</p>
<p class="p3">Потом она смотрит в сторону Эльминстра.</p>
<p class="p6">“Поэтому объяснение дадим мы.”</p>
<p class="p2"><b>Спектакль с наутилоидом</b></p>
<p class="p3">План Лиреаны:</p>
<p class="p4">•<span class="Apple-tab-span">	</span>после падения барьера Цурлагол должен увидеть угрозу;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>угроза будет оформлена как иллюзорное вторжение наутилоида;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>Эльминстр публично “отразит” его;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>люди увидят, что иллитидская угроза реальна или хотя бы возможна;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>старая власть будет выглядеть беспомощной;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>Имаскар появится как сила, способная защитить город;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>после этого последует заявление.</p>
<p class="p3">Лиреана честно говорит:</p>
<p class="p6">“Мы не можем выйти к толпе и сказать: ‘Добрый день, ваши карты лгали, ваш горизонт был клеткой, ваши советники служат пожирателям разума, а мы нашли древнюю бумагу, которая делает нас удобной альтернативой власти’. Это плохая речь. Её перебьют камнями.”</p>
<p class="p3">Если игроки возмутятся, что это новая ложь, она не спорит:</p>
<p class="p6">“Да. Это сцена. Но сцена, которая ведёт людей к правде, иногда полезнее правды, которая ведёт людей к панике.”</p>
<p class="p3">Каэл может резко добавить:</p>
<p class="p6">“Или мы можем сказать всё прямо и смотреть, как город сам несёт головы Оракулам, потому что те хотя бы обещают вернуть привычный мир.”</p>
<p class="p3">Лиреана:</p>
<p class="p6">“Столетнюю ложь нельзя разбить одной правдивой фразой. Её нужно заменить историей, которую люди смогут пережить.”</p>
<p class="p5">​</p>
<p class="p1"><b>8. Эльминстр репетирует речь</b></p>
<p class="p3">Эльминстр здесь должен быть живым, молодым, перегруженным, но вдохновлённым.</p>
<p class="p3">Он не “дед-архимаг из будущего”. Он молодой опасный маг, который понимает, что сейчас ему предстоит сыграть роль, которая может войти в историю.</p>
<p class="p3">И он гордится игроками. Не сладко, не пафосно, а по-настоящему: они сделали то, что даже Имаскар не смог.</p>
<p class="p2"><b>Сцена</b></p>
<p class="p3">Игроки видят Эльминстра в соседней комнате или у края зала.</p>
<p class="p3">Он стоит перед пустым пространством и репетирует речь.</p>
<p class="p3">В воздухе перед ним то появляется силуэт наутилоида, то исчезает. Иногда он выглядит слишком страшно, иногда слишком театрально. Эльминстр раздражённо щёлкает пальцами, меняет форму щупалец, угол тени, высоту “корабля”.</p>
<p class="p3">Он бормочет:</p>
<p class="p6">“Нет, слишком красиво. Люди не боятся красивого, они потом это рисуют на кружках…”</p>
<p class="p3">Или:</p>
<p class="p6">“Если щупальца ниже — площадь увидит. Если выше — дворяне увидят. Мне нужны оба. Проклятье.”</p>
<p class="p3">Потом замечает игроков.</p>
<p class="p6">“А вот и вы.”</p>
<p class="p3">Пауза.</p>
<p class="p6">“Живые. С Пактом. После гор, Оракулов и всего того, что, судя по вашему виду, я пока не хочу знать за завтраком.”</p>
<p class="p3">Он улыбается устало, но искренне.</p>
<p class="p6">“Хорошая работа.”</p>
<p class="p3">Если игроки удивятся, что он хвалит:</p>
<p class="p6">“Не привыкайте. Я всё ещё считаю вас катастрофой с ногами. Но сегодня вы были нашей катастрофой. Это приятно.”</p>
<p class="p2"><b>Эльминстр гордится игроками</b></p>
<p class="p3">Он говорит уже тише:</p>
<p class="p6">“Вы понимаете, что сделали? Не для Имаскара. Не для Ашерона. Для карты. Вы дошли туда, куда все привыкли не доходить, и принесли обратно вещь, которая заставит взрослых людей в дорогих плащах переписывать прошлое.”</p>
<p class="p3">Потом ещё мягче:</p>
<p class="p6">“Это редкий вкус. Запомните. Обычно история переписывает таких, как вы. Сегодня вы притащили ей чернила.”</p>
<p class="p2"><b>Предложение выпить</b></p>
<p class="p3">Эльминстр может предложить после всего выпить.</p>
<p class="p6">“Когда всё это закончится — барьер, город, наутилоид, речи, возможная паника, возможные казни, возможная война, — я предлагаю выпить.”</p>
<p class="p3">Если кто-то спрашивает, за что:</p>
<p class="p6">“За то, что мы будем живы. Не оригинально, зато практично.”</p>
<p class="p3">Потом добавляет:</p>
<p class="p6">“И за вас. Потому что, как бы мне ни хотелось этого не признавать, без вас мы бы до сих пор спорили с картами.”</p>
<p class="p3">Это хорошая человеческая сцена. Она делает Эльминстра не только опасным магом, но и будущим союзником, который эмоционально понимает вес момента.</p>
<p class="p5">​</p>
<p class="p1"><b>9. Севериан делает портальный камень</b></p>
<p class="p3">Севериан в начале сцены отсутствует, потому что он работает.</p>
<p class="p3">Его нужно ввести отдельно, с сильным визуалом.</p>
<p class="p2"><b>Мастерская Севериана</b></p>
<p class="p3">Игроков проводят или вызывают в боковую мастерскую.</p>
<p class="p3">Там хаос другого типа: не политический, а технический.</p>
<p class="p3">На столах:</p>
<p class="p4">•<span class="Apple-tab-span">	</span>схемы из документов Саэля;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>нетерильские формулы;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>каменные заготовки;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>металлические кольца;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>сосуды с жидким светом;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>обломки старого портального узла;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>инструменты Имаскара;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>защитные круги;</p>
<p class="p4">•<span class="Apple-tab-span">	</span>карта между особняком и замком.</p>
<p class="p3">В центре — камень, который ещё не портал, но уже не просто камень.</p>
<p class="p3">Он зависает в воздухе, дрожит, по его поверхности ползут трещины света. Пространство рядом с ним слегка “складывается”: стол за камнем кажется ближе, чем должен быть.</p>
<p class="p3">Севериан выглядит как человек, который трижды забыл поесть и считает это нормой.</p>
<p class="p2"><b>Текст для зачтения</b></p>
<p class="p6">В мастерской пахнет горячим камнем, озоном и чернилами.</p>
<p class="p7"><br></p>
<p class="p6">Севериан стоит у рабочего круга, где в воздухе висит серый камень размером с человеческую голову. По его поверхности расходятся тонкие светящиеся жилы. Иногда они раскрываются, и на миг вы видите не внутренность камня, а кусок другого места: мокрый камень, знакомую стену, край замковой кладки.</p>
<p class="p7"><br></p>
<p class="p6">Севериан не оборачивается сразу.</p>
<p class="p7"><br></p>
<p class="p6">“Нет, нет, нет… если развернуть складку до стабилизации, он порвёт не расстояние, а полмастерской…”</p>
<p class="p7"><br></p>
<p class="p6">Потом замечает вас.</p>
<p class="p7"><br></p>
<p class="p6">“О. Вы вернулись. Великолепно. Не трогайте ничего, что светится. И ничего, что не светится, тоже.”</p>
<p class="p2"><b>Севериан объясняет камни</b></p>
<p class="p6">“Документы из вашего замка оказались не инструкцией к готовой сети, а описанием принципа. Нетерил не телепортировал людей так, как любят рассказывать сказки. Он складывал расстояние между двумя подготовленными точками.”</p>
<p class="p3">Он показывает на камень.</p>
<p class="p6">“Это первый рабочий образец. Парный камень уже размещён у вашего замка.”</p>
<p class="p3">Если игроки спрашивают, кто разместил:</p>
<p class="p3">Севериан устало:</p>
<p class="p6">“Ивен.”</p>
<p class="p3">Пауза.</p>
<p class="p6">“Разумеется, <a href="dmref://E392CEFB-E7DE-4680-BA79-16B057D1D499">Ивен</a>. Этот человек однажды доставит письмо в могилу раньше покойника.”</p>
<p class="p3">Можно дать Хальверу сухо добавить:</p>
<p class="p6">“Мы стараемся не поощрять его, но он всё равно успевает.”</p>
<p class="p2"><b>Важные правила портала</b></p>
<p class="p3">Севериан объясняет:</p>
<p class="p6">“После активации камни нельзя переставить. Они врастают не в землю, а в расстояние. Уничтожить их можно только мощной антимагией.”</p>
<p class="p6">“Обычный удар, огонь, молния, молот, даже большинство заклинаний — бессмысленны. Камень уже не совсем предмет.”</p>
<p class="p6">“Аберрации через такой проход пройти не должны. Не из-за стены. Из-за отсутствия того, что система признаёт душевной сигнатурой.”</p>
<p class="p3">Если игроки вспоминают личинок:</p>
<p class="p6">“Да. Заражённый человек пройдёт. Личинка — нет.”</p>
<p class="p3">Севериан замолкает.</p>
<p class="p6">“Последствия внутри черепа можете представить сами.”</p>
<p class="p2"><b>Первый портал</b></p>
<p class="p3">Севериан даёт им второй камень пары или активирует его прямо в особняке.</p>
<p class="p3">Камень застывает в воздухе, начинает расползаться по пространству, как трещина в стекле. Потом трещина становится проходом.</p>
<p class="p3">С другой стороны видна часть их замка.</p>
<p class="p3">Не иллюзия. Не картинка. Настоящий проход.</p>
<p class="p3">Описание:</p>
<p class="p6">Камень поднимается выше, трещит, но не ломается. Его поверхность раскрывается линиями света. Пространство вокруг него тянется, как ткань под пальцами.</p>
<p class="p7"><br></p>
<p class="p6">Потом воздух между трещинами проваливается внутрь, и вы видите замок. Не отражение. Не видение. Камень стены, холодный свет, знакомый угол двора.</p>
<p class="p7"><br></p>
<p class="p6">Расстояние между особняком Имаскара и вашим замком становится толщиной в один шаг.</p>
<p class="p3">Севериан:</p>
<p class="p6">“Поздравляю. Вы только что получили не дверь. Вы получили первую артерию будущего региона.”</p>
<p class="p5">​</p>
<p class="p1"><b>10. Раскрытие источника барьера</b></p>
<p class="p3">После портального камня Севериан или <a href="dmref://32694CE8-CEA7-4A4F-95FE-005CAF66FE12">Ашерон</a> объясняют источник барьера.</p>
<p class="p3">Важно: источник не в горах. Он у замка, под плато, в <b>кратере лимитирующих камней</b>.</p>
<p class="p2"><b>Объяснение</b></p>
<p class="p3">Севериан показывает карту.</p>
<p class="p6">“Мы сначала думали, что источник барьера находится в горах, рядом с упавшим островом. Это было логично. И неверно.”</p>
<p class="p3">Он указывает на область рядом с замком.</p>
<p class="p6">“Ваш кратер лимитирующих камней. Место падения огромного осколка мифаллара.”</p>
<p class="p3">Пауза.</p>
<p class="p6">“Он уже не работает как мифаллар. Кто-то переделал его. Грубо. Мощно. Неэлегантно. Но масштаб… масштаб чудовищный.”</p>
<p class="p3"><a href="dmref://32694CE8-CEA7-4A4F-95FE-005CAF66FE12">Ашерон</a>:</p>
<p class="p6">“Этот камень заставляет регион помнить неверную границу.”</p>
<p class="p3">Севериан:</p>
<p class="p6">“Изнутри люди видят хребты, пустоши, мёртвые края. Снаружи видят выжженную землю и обрыв в море. Это не обычная иллюзия. Это взаимная договорённость восприятия, закреплённая в земле.”</p>
<p class="p3">Если игроки спрашивают, кто это сделал:</p>
<p class="p6">“Не знаем. Пока. Нетерильская основа очевидна. Переделка — позднее. Возможно, Цурлагол. Возможно, Оракулы. Возможно, кто-то третий, кто думал, что спасает регион.”</p>
<p class="p3">Эта неопределённость важна.</p>
<p class="p5">​</p>
<p class="p1"><b>11. Почему нужен Метеоритный дождь</b></p>
<p class="p3">Севериан объясняет, что добраться до камня невозможно.</p>
<p class="p6">“Камень похоронен под землёй, породой, оплавленным грунтом и собственным искажением. Его нельзя просто выкопать. Можно потратить месяцы, потерять людей, привлечь Оракулов и в итоге обнаружить, что ты копал не в том месте, потому что барьер убедил карту ошибиться.”</p>
<p class="p3">Каэл:</p>
<p class="p6">“Значит, не копаем.”</p>
<p class="p3"><a href="dmref://32694CE8-CEA7-4A4F-95FE-005CAF66FE12">Ашерон</a>:</p>
<p class="p6">“Уничтожаем кратер.”</p>
<p class="p3">Севериан не рад этому, но согласен.</p>
<p class="p6">“Это грубо.”</p>
<p class="p3">Каэл:</p>
<p class="p6">“Зато понятно.”</p>
<p class="p3"><a href="dmref://32694CE8-CEA7-4A4F-95FE-005CAF66FE12">Ашерон</a> отдаёт знак Хальверу или одному из слуг. Приносят ларец.</p>
<p class="p5">​</p>
<p class="p1"><b>12. Ларец со свитком Метеоритного дождя</b></p>
<p class="p2"><b>Образ</b></p>
<p class="p3">Ларец должен ощущаться как настоящее сокровище.</p>
<p class="p3">Он не большой, но очень тяжёлый. Матовый металл, тёмное дерево, серебряные швы, четыре печати Имаскара. На крышке нет украшений, только маленький знак, похожий на падающую звезду, заключённую в квадрат.</p>
<p class="p3">Рядом — перстень-ключ.</p>
<p class="p2"><b>Текст Ашерона</b></p>
<p class="p6">“Это не награда.”</p>
<p class="p3">Пауза.</p>
<p class="p6">“Награды дают за завершённые дела. Ваше дело только стало достаточно большим, чтобы стоить таких расходов.”</p>
<p class="p3">Он кладёт руку на ларец, но не открывает.</p>
<p class="p6">“Внутри свиток Метеоритного дождя. Не копия, не учебная запись, не украшение архива. Настоящий. Стабилизированный. Одноразовый.”</p>
<p class="p3">Каэл:</p>
<p class="p6">“Четыре удара. Сорок футов каждая зона. Огонь и камень. Если навести плохо — разрушите не то. Если открыть не там — потеряете единственный шанс.”</p>
