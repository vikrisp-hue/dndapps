5. Мира Вейн отдаёт инструкции Серым Ключам
Мира должна ощущаться не как “NPC в углу”, а как человек, который уже двигает сеть.
Она говорит тихо, но игроки могут услышать часть приказов.
Инструкции Миры
Роэну “Сухая Тень”
“Роэн. Дороги к Цурлаголу, старый тракт, подходы к портам. Никакой героики. Мне нужны глаза, не труп.”
Роэн:
“Если хвост?”
Мира:
“Пусть думает, что потерял тебя сам.”
Талису Грею
“Талис. Подготовь три версии слуха. Первая — что внешний мир жив. Вторая — что власть Цурлагола скрывала дороги. Третья — что древний род уже знал, но ждал доказательств. Третью использовать только после сигнала Лиреаны.”
Талис:
“С подписью?”
Мира:
“Без. Люди верят слухам лучше, когда думают, что украли их сами.”
Йордану Крею
“Йордан. Не трогать городских крикунов без приказа. Нужны не исчезновения, а страх перед исчезновениями.”
Йордан усмехается.
Мира:
“Я сказала — без приказа.”
Эллару Дорну через курьера/записку
“Эллару передать: сжечь только вторые копии. Первые пусть найдут не те люди. И пусть найдут слишком поздно.”
Это показывает: Имаскар уже готовит информационную войну.
Мира позже извиняется перед игроками
После основной сцены, когда суета чуть стихает, Мира может подойти отдельно.
Не на публике. Не театрально.
“Я не доверяла вам.”
Пауза.
“Это было разумно.”
Ещё пауза.
“Но вы принесли Пакт. Не продали, не спрятали, не попытались открыть чужими руками. Значит, я должна исправить оценку.”
Если игроки ждут извинения:
“Не ждите красивых слов. Я редко ими пользуюсь. Но да — в этом я была неправа.”
И потом важная фраза:
“С этого момента я буду считать вас не наёмниками, а стороной. Это опаснее. Но честнее.”
