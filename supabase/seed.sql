Шум. Крики. Часть людей повторяет новое имя. Часть откровенно в ужасе.
“Я, Ашерон Имаскар, принимаю титул Первого Лорда Великого Имаскара.”
​
Заявление второе: отмена рабства
Вот это должно прозвучать первым крупным законом, чтобы толпа поняла: смена власти не только про гербы.
Ашерон кладёт на стол пачку старых городских реестров.
“Первый закон Великого Имаскара прост.”

“Рабство отменяется.”
Пауза. Толпа на секунду не понимает, что услышала.
“С этого дня ни один человек, тифлинг, эльф, полуорк, гоблин, дварф или представитель иной разумной крови не может быть признан собственностью другого лица.”

“Все долговые цепи, наследственные узы, рабские метки, городские реестры владения телом и трудом — аннулируются.”
Крики. Уже настоящие. Кто-то падает на колени. Кто-то из бывших владельцев начинает возмущаться.
Каэл делает шаг вперёд, и его люди на площади сразу напрягаются.
Ашерон продолжает:
“Те, кто удерживает рабов после этого заявления, будут признаны мятежниками против нового порядка.”

“Те, кто освобождён сегодня, не обязаны благодарить меня. Свобода не милость. Милостью её называли те, кто крал её у вас.”
Это сильный момент: он не просит любви. Он берёт власть через закон.
​
Заявление третье: подземные жители
После отмены рабства Ашерон обращается к тем, кто жил под городом: беглые, изгнанники, подземные общины, преступные группы, бывшие рабы, люди без статуса.
“Теперь я обращаюсь к тем, кто живёт под этим городом.”

“К тем, кого загнали в тоннели. К тем, кто прятался от долговых цепей, от старой стражи, от ложных обвинений, от голода или от собственной вины.”
Он делает паузу.
“Великий Имаскар предлагает переговоры.”
Толпа реагирует неоднозначно. Кто-то кричит: “Там убийцы!” Кто-то: “Там наши дети!” Кто-то: “Они нас грабили!”
Ашерон не спорит.
“Среди вас есть невиновные. Среди вас есть беглые рабы. Среди вас есть люди, которых старая власть превратила в грязь, а потом удивлялась, что грязь кусается.”

“Но среди вас есть и мерзавцы. Убийцы. Торговцы людьми. Те, кто сделал подземелья своим маленьким царством страха.”
Он смотрит в сторону входов в нижние районы, будто говорит не только с толпой, но и с теми, кто слушает из-под земли.
“Поэтому предложение одно: выходите на переговоры.”

“Не на казнь. Не на поклон. На переговоры.”

“Те, кто хочет жить на свету, получат такую возможность.”

“Те, кто хочет продолжать править страхом внизу, узнают, что у нового города есть достаточно длинные руки.”
Это создаёт идеальный конфликт на будущие задания: часть подземных жителей благодарна и выйдет; часть преступников попытается воспользоваться амнистией; часть начнёт войну за нижние районы.
​
Заявление четвёртое: тифлинги больше не “демоны”
Теперь Ашерон переходит к самому взрывоопасному пункту.
На краю площади стоят представители тифлингов. Они не чувствуют себя в безопасности. Город веками называл их демонами.
Ашерон поднимает несколько документов.
“Теперь о тех, кого этот город называл демонами.”
Толпа мгновенно меняется. Шум становится резче. Кто-то плюёт. Кто-то отступает. Кто-то ищет глазами рогатые силуэты у края площади.
Ашерон говорит жёстче:
“Вам говорили, что тифлинги — порождения зла.”

“Вам говорили, что с ними нельзя говорить.”

“Вам говорили, что их кровь делает их рабами, врагами, скотом или угрозой по праву рождения.”
Он поднимает первый документ.
“Вот отчёт старого управления городской пропаганды.”

“Цитата: ‘Программа демонизации рогатых племён идёт успешно. При сохранении текущего давления следующее поколение будет воспринимать собственное порабощение как естественное следствие крови’.”
Толпа гудит.
Он поднимает второй документ.
“Вот приказ о распространении слухов после нападения на караван. Виновные не были установлены. Но в приказе заранее указано: ‘В публичном изложении связать происшествие с демонами верхних троп’.”
Третий документ.
“Вот реестр детей, рождённых от смешанных связей. Пометка чиновника: ‘Не допускать к городским ремёслам. При необходимости использовать как доказательство разложения крови’.”
Четвёртый.
“Вот донесение о торговцах, которые пытались вести обмен с тифлингами. Их обвиняли не в преступлении, а в ‘ослаблении страха перед внешним видом врага’.”
Ашерон опускает документы.
“Это не правосудие. Это разведение ненависти.”
Он говорит громче:
“С этого дня прежние обвинения против племени тифлингов, основанные на их крови, происхождении, рогах, коже или старой городской пропаганде, сняты.”

“Тифлинги могут входить в Великий Имаскар. Торговать. Давать показания. Искать защиты нового закона.”

“Любой, кто нападёт на них только за то, что старая власть научила его бояться, будет отвечать перед новым судом.”
Очень важно: он не объявляет тифлингов невинными во всём. Он снимает именно расовую/пропагандистскую вину.
“Это не значит, что преступления будут прощены. Если тифлинг убил — он ответит как убийца. Если человек убил — он ответит как убийца. Но отныне кровь не является приговором.”
Вот это взрослый и сильный баланс, особенно с учётом того, что игроки знают про резню диких эльфов.
​
Заявление пятое: публичная библиотека
Это должно стать неожиданностью даже для Имаскара.
Ашерон смотрит на толпу. Он видит настроение: страх, гнев, надежду, недоверие. Он понимает, что просто силой и документами новый порядок не удержать.
И тут он принимает решение на сцене.
Это заявление не знали заранее ни Каэл, ни Севериан, ни Лиреана, ни Мира.
Ашерон некоторое время молчит. Севериан чуть поворачивает голову, потому что понимает: отец сейчас отходит от подготовленной речи.
Ашерон говорит:
“И ещё одно.”
Лиреана впервые заметно напрягается.
“Сто лет вами правили не только мечом, страхом и ложными картами.”

“Вами правили невежеством.”
Он смотрит на людей.
“Дом Имаскар хранил библиотеку. Старую. Неполную. Опасную. Дорогую. Достаточно большую, чтобы многие здесь назвали её сокровищницей.”
Севериан в этот момент реально в шоке. Для него библиотека — сердце рода.
Ашерон продолжает:
“Эта библиотека будет перенесена в Великий Имаскар.”
Толпа сначала не понимает. Потом начинается шум.
“Часть её станет общественной.”

“Не для каждого праздного любопытного. Не для тех, кто ищет оружие в каждой строке. Но для тех, чья личность на хорошем счету, кто доказал намерение учиться, служить, лечить, строить, писать, считать, вести ремесло или искать правду.”
Севериан тихо, почти шёпотом:
“Отец…”
Ашерон не смотрит на него.
“Город, который сто лет держали во лжи, не станет свободным, если мы просто сменим вывеску на дворце.”

“Знание больше не будет только стеной вокруг рода. Часть его станет лестницей для города.”
Это прям взрыв. Кто-то плачет. Кто-то не верит. Кто-то из старой знати в ужасе, потому что доступ к знаниям разрушает старые зависимости.
Лиреана быстро берёт себя в руки и уже понимает политическую гениальность этого жеста: Ашерон покупает не только власть, а будущее поколение чиновников, магов, инженеров и лояльных людей.
​
Благодарность Эллару Дорну
Теперь Ашерон переходит к назначениям и благодарностям.
Он публично благодарит тех, кого можно легально показать.
“Магистрат Эллар Дорн.”
Эллар выходит или делает шаг вперёд. Для толпы он чиновник старого города, но теперь выясняется, что он помог раскрыть ложь.
“Ваше содействие, переданные документы и риск, на который вы пошли внутри старой администрации, позволили вскрыть часть заговора до того, как он стал войной.”
Это важный момент: Ашерон показывает, что не все в старой системе были врагами.
“Великий Имаскар будет нуждаться не только в новых людях, но и в тех, кто знал старую машину изнутри и не дал ей перемолоть остатки правды.”
Эллар получает должность, например:
Магистр городских реестров и переходного права или Советник по гражданской администрации.
​
Назначения на сцене
Каэл
“Каэл Имаскар назначается Лордом-Маршалом дорог и городской защиты.”
Функция: охрана дорог, новые заставы, подавление мятежей, защита открытого региона.
Севериан
“Севериан Имаскар назначается Хранителем Пакта и Главным Архиварием Великого Имаскара.”
Функция: Пакт, документы, библиотека, нетерильские технологии, порталы.
Севериан всё ещё в шоке из-за библиотеки, но держится.
Лиреана
“Лиреана Имаскар назначается Леди Договоров и Голосом Великого Имаскара.”
Функция: переговоры, внешние связи, купцы, первые отношения с открывшимся миром.
Эльминстр
“Эльминстр, внешний союзник Дома и защитник города, получает должность Первого Магистра.”
Это звучит чуть пафосно, и Эльминстр может позже ворчать, что титул ужасно громкий.
​
Почему он не упоминает Миру и игроков
Ашерон перебирает бумаги. Он доходит до следующего листа, но не зачитывает.
Игроки и Мира стоят рядом.
Ашерон слегка наклоняется к ним, не меняя выражения лица, и почти не двигая губами говорит:
“Ваши должности будут несколько секретны.”

“Простите, что без огласки.”
Мира не выглядит удивлённой. Скорее наоборот: она бы обиделась, если бы её назвали публично.
Игроки могут почувствовать разницу:
Публично их могут назвать героями и владельцами замка, но настоящие должности, настоящая структура и настоящая власть будут объявлены позже — за закрытыми дверями.
​
Признание земли игроков
Это можно сделать публично, но без раскрытия их будущей секретной роли.
Ашерон говорит:
“Также перед городом, Пактом и новым правом я признаю за добывшими Пакт владение замком Альбина и землями вокруг него.”

“Двадцать пять гектаров вокруг старой заставы переходят под их управление и защиту.”

“Этот замок будет стоять на дороге между старой ложью и открытым миром.”
Это публично. Их видят. Их запоминают. Божественность отзывается.
Но он не говорит: “Они будут главами новой имперской структуры”.
​
Божественный отклик игроков
После признания и реакции толпы можно дать короткий внутренний момент.
Когда толпа поворачивается к вам, это не похоже на благодарность одного спасённого человека.

Это тяжелее. Грязнее. Опаснее.

На вас смотрят как на тех, кто принёс Пакт, кто стоял рядом с новым лордом, кто получил землю и имя на карте.

Где-то внутри Искры отвечают. Не светом. Не голосом. Давлением.

Мир не молится вам.

Но впервые достаточно людей одновременно признают: вы теперь часть его власти.
Это не обязательно новый уровень божественности, но явный скачок влияния.
​
Финал публичной сцены
Ашерон завершает:
“Сегодня Великий Имаскар не становится безопасным.”

“Он становится настоящим.”

“А настоящий город должен иметь дороги, закон, память и врагов, которых он не боится назвать.”
Он закрывает Пакт.
“Старая ложь закончилась. Новый порядок начинается сейчас.”
На этом площадь взрывается шумом.
Кто-то кричит имя Имаскара. Кто-то имя Ашерона. Кто-то требует наказать старую власть. Кто-то зовёт освобождённых рабов. Кто-то смотрит на тифлингов с ненавистью, но уже боится ударить. Кто-то спрашивает, как попасть в библиотеку. Кто-то тихо уходит в подземелья, чтобы предупредить тех, кто не собирается выходить на переговоры.
И где-то среди толпы Серые Ключи уже работают.
​
Сцена после назначения: главная мэрия города
После публичной церемонии игроков и Миру приглашают в главную мэрию города.
Теперь это уже не площадь, не речь, не театр.
Это закрытая комната власти.
Обстановка
Большой зал городской администрации. Старые символы Цурлагола ещё не сняты. На стене карта города. На столе новые печати. За окнами всё ещё слышен шум толпы.
В комнате:
•	Ашерон;
•	Каэл;
•	Севериан;
•	Лиреана;
•	Мира Вейн;
•	игроки;
•	возможно, Эльминстр, если хочешь добавить живой комментарий;
•	несколько писцов, которых потом выводят.
Ашерон ждёт, пока двери закроются.
Потом говорит:
“Теперь — о должностях, которые не выкрикивают с площади.”
​
Назначение Миры
Ашерон смотрит на Миру.
“Мира Вейн.”
Она спокойно делает шаг вперёд.
“Серые Ключи перестают быть только наследственной сетью Дома Имаскар.”

“С этого дня они становятся основой Разведывательного корпуса Великого Имаскара.”
Пауза.
“Вы становитесь его главой.”
Мира не кланяется низко. Просто принимает.
“Принято.”
Ашерон:
“Ваши задачи: внутренняя безопасность, внешняя разведка, выявление Оракулов, защита архивов, контроль слухов и наблюдение за теми, кто решит, что новый порядок можно купить так же легко, как старый.”
Мира:
“Мне понадобятся люди, которых публично не существует.”
Ашерон:
“Именно поэтому я не назвал вас со сцены.”
​
Назначение игроков: Орден Защитников
Теперь Ашерон обращается к партии.
“Вы не чиновники. И не солдаты в строю.”

“Это неудобно.”

“И ценно.”
Он раскрывает новый документ.
“Великому Имаскару понадобится структура, способная делать то, что армия делает слишком громко, разведка слишком тайно, а администрация слишком медленно.”
Каэл добавляет:
“Руины. Чудовища. дороги, старые хранилища, пропавшие караваны, следы Оракулов, угрозы за пределами закона.”
Лиреана:
“И задачи, которые официально будут называться защитой региона, даже если на деле они окажутся грязнее.”
Ашерон:
“Создаётся Орден Защитников Великого Имаскара.”
Что это такое
По факту это имперская гильдия авантюристов.
Но в мире это звучит солиднее:
•	структура для особых поручений;
•	легальный способ нанимать авантюристов;
•	инструмент зачистки руин и угроз;
•	способ контролировать опасных людей;
•	механизм выдачи заданий от власти;
•	будущая сеть полевых агентов.
Ашерон:
“Он будет принимать заказы от города, Дома, дорог, внешних союзников и граждан, если угроза признана значимой.”

“Но право высшего отбора, направления и допуска к самым опасным поручениям получаете вы.”
Три главы структуры
Игроки становятся не просто членами, а тремя главами новой структуры.
Можно дать им общий титул:
Основатели Ордена Защитников
Ашерон:
“Вы будете первыми главами Ордена.”

“Не потому, что вы удобны.”

“Потому что вы уже доказали, что способны идти туда, где удобные люди умирают или врут.”
Каэл:
“Вы будете получать задачи, которые нельзя доверить городской страже.”
Мира:
“И иногда задачи, о которых городская стража не должна знать.”
Лиреана:
“А публично вы будете теми, кто защищает дороги, руины, караваны и людей нового государства.”
Севериан:
“И теми, кто будет приносить мне всё, что выглядит древним, опасным или не должно лежать без присмотра.”
Эльминстр, если присутствует:
“Особенно если оно светится, шепчет или обещает власть. Такие вещи, как показывает практика, вы всё равно находите первыми.”
​
Разделение ролей игроков внутри Ордена
Можно не назначать жёстко, но Ашерон может предложить рамку.
Марина / гоблинша
“Расследования, слабые места, внедрение, работа с информацией. Ордену понадобится тот, кто видит трещины раньше, чем они становятся провалами.”
Ваня / воин
“Прорыв, подавление угроз, мобильные операции. Когда нужно быстро ударить туда, где враг считал себя недосягаемым.”
Лена / паладин
“Защита, удержание, полевая власть. Когда люди должны выжить не потому, что мир добр, а потому что кто-то встал между ними и смертью.”
Ашерон:
“Это не клятва рыцарей. Не братство героев. Не храм.”

“Это инструмент нового государства.”
Пауза.
“Но каким он станет — зависит от вас.”
